-- =============================================================================================
-- AUTHENTICATION TABLES
-- =============================================================================================

-- Core entities
CREATE TABLE authentication.users (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY,
	username VARCHAR(50) NOT NULL,
	email VARCHAR(100) NOT NULL,
	password_hash VARCHAR(255) NOT NULL,
	is_active BOOLEAN NOT NULL DEFAULT TRUE,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT pk_users
		PRIMARY KEY(id),
	CONSTRAINT uq_users_username
		UNIQUE(username),
	CONSTRAINT uq_users_email
		UNIQUE(email)
);

CREATE TABLE authentication.roles (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY,
	name VARCHAR(50) NOT NULL,
	description VARCHAR(255),
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT pk_roles
		PRIMARY KEY(id),
	CONSTRAINT uq_roles_name
		UNIQUE(name)
);

-- Relationships
CREATE TABLE authentication.user_roles (
	user_id BIGINT NOT NULL,
	role_id BIGINT NOT NULL,
	assigned_by BIGINT,
	assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT pk_user_roles
		PRIMARY KEY(user_id, role_id),
	CONSTRAINT fk_user_roles_user
		FOREIGN KEY(user_id)
		REFERENCES authentication.users(id),
	CONSTRAINT fk_user_roles_role
		FOREIGN KEY(role_id)
		REFERENCES authentication.roles(id),
	CONSTRAINT fk_user_roles_assigned_by
		FOREIGN KEY(assigned_by)
		REFERENCES authentication.users(id)
);

-- Session management
CREATE TABLE authentication.sessions (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY,
	user_id BIGINT NOT NULL,
	token VARCHAR(255) NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	expires_at TIMESTAMPTZ NOT NULL,
	closed_at TIMESTAMPTZ,
	is_active BOOLEAN NOT NULL DEFAULT TRUE,
	CONSTRAINT pk_sessions
		PRIMARY KEY(id),
	CONSTRAINT fk_sessions_user
		FOREIGN KEY(user_id)
		REFERENCES authentication.users(id),
	CONSTRAINT uq_sessions_token
		UNIQUE(token),
	CONSTRAINT ck_sessions_dates
		CHECK(
			expires_at > created_at
			AND (
				closed_at IS NULL
				OR closed_at > created_at
			)
		)
);

