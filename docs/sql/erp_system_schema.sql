CREATE TABLE commerce.shippers (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY,
	shipper_type VARCHAR(20) NOT NULL,
	employee_id BIGINT,
	logistic_company_id BIGINT,
	independent_shipper_id BIGINT,
	is_active BOOLEAN NOT NULL DEFAULT TRUE,
	CONSTRAINT pk_shippers
		PRIMARY KEY(id),
	CONSTRAINT fk_shippers_employee_id
		FOREIGN KEY(employee_id)
		REFERENCES commerce.employees(id),
	CONSTRAINT fk_shippers_logistic_company_id
		FOREIGN KEY(logistic_company_id)
		REFERENCES commerce.logistics_companies(id),
	CONSTRAINT fk_shippers_independent_shipper_id
		FOREIGN KEY(independent_shipper_id)
		REFERENCES commerce.independent_shippers(id),
	CONSTRAINT uq_shippers_employee_id
		UNIQUE(employee_id),
	CONSTRAINT uq_shippers_logistic_company_id
		UNIQUE(logistic_company_id), 
	CONSTRAINT uq_shippers_independent_shipper_id
		UNIQUE(independent_shipper_id),
	CONSTRAINT ck_shippers_shipper_type
		CHECK(
			(shipper_type = 'employee'
			AND employee_id IS NOT NULL
			AND logistic_company_id IS NULL
			AND independent_shipper_id IS NULL)
			OR
			(shipper_type = 'company'
			AND employee_id IS NULL
			AND logistic_company_id IS NOT NULL
			AND independent_shipper_id IS NULL)
			OR
			(shipper_type = 'independent'
			AND employee_id IS NULL
			AND logistic_company_id IS NULL
			AND independent_shipper_id IS NOT NULL)
		)
);

