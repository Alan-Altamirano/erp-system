	supplier_product_id BIGINT NOT NULL,
	product_code VARCHAR(50) NOT NULL,
	product_name VARCHAR(150) NOT NULL,
	unit_of_measure VARCHAR(20) NOT NULL,
	quantity DECIMAL(10,2) NOT NULL,
	unit_cost DECIMAL(10,2) NOT NULL,
	discount_rate DECIMAL(5,2) NOT NULL,
	discount_amount DECIMAL(12,2) NOT NULL,
	tax_rate DECIMAL(5,2) NOT NULL,
	tax_amount DECIMAL(12,2) NOT NULL,
	line_total DECIMAL(12,2) NOT NULL,
	CONSTRAINT pk_supplier_invoice_details
		PRIMARY KEY(id),
	CONSTRAINT fk_supplier_invoice_details_supplier_invoice_id
		FOREIGN KEY(supplier_invoice_id)
		REFERENCES commerce.supplier_invoices(id),
	CONSTRAINT fk_supplier_invoice_details_supplier_product_id
		FOREIGN KEY(supplier_product_id)
		REFERENCES commerce.supplier_products(id),
	CONSTRAINT ck_supplier_invoice_details_amounts
		CHECK(
			unit_cost > 0
			AND quantity > 0
			AND discount_rate >= 0 AND discount_rate <= 100
			AND discount_amount >= 0
			AND tax_rate >= 0 AND tax_rate <= 100
			AND tax_amount >= 0
			AND line_total >= 0
		)
);

CREATE TABLE commerce.product_batches (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY,
	purchase_receipt_detail_id BIGINT NOT NULL,
	batch_number VARCHAR(100) NOT NULL,
	manufacture_date DATE,
	expiration_date DATE,
	received_date DATE NOT NULL,
	initial_quantity DECIMAL(12,2) NOT NULL,
	unit_cost DECIMAL(12,2) NOT NULL,
	status VARCHAR(20) NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT pk_product_batches
		PRIMARY KEY(id),
	CONSTRAINT fk_product_batches_purchase_receipt_detail_id
		FOREIGN KEY(purchase_receipt_detail_id)
		REFERENCES commerce.purchase_receipt_details(id),
	CONSTRAINT ck_product_batches_manufacture_date
		CHECK(
			manufacture_date IS NULL 
			OR manufacture_date <= received_date
		),
	CONSTRAINT ck_product_batches_expiration_date
		CHECK(
			expiration_date IS NULL 
			OR expiration_date > received_date 
			OR expiration_date > manufacture_date 
		),
	CONSTRAINT ck_product_batches_quantity_and_cost
		CHECK(
			initial_quantity > 0
			AND unit_cost > 0
		),
	CONSTRAINT ck_product_batches_dates
		CHECK(updated_at >= created_at)
);

CREATE TABLE commerce.stocks (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY,
	warehouse_id BIGINT NOT NULL,
	product_batch_id BIGINT NOT NULL,
	current_quantity DECIMAL(12,2) NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT pk_stocks
		PRIMARY KEY(id),
	CONSTRAINT fk_stocks_warehouse_id
		FOREIGN KEY(warehouse_id)
		REFERENCES commerce.warehouses(id),
	CONSTRAINT fk_stocks_product_batch_id
		FOREIGN KEY(product_batch_id)
		REFERENCES commerce.product_batches(id),
	CONSTRAINT uq_stocks_warehouse_product_batch
		UNIQUE(warehouse_id, product_batch_id),
	CONSTRAINT ck_stocks_current_quantity
		CHECK(current_quantity >= 0),
	CONSTRAINT ck_stocks_dates
		CHECK(updated_at >= created_at)
);

CREATE TABLE commerce.stock_movements (
